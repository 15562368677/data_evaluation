def esc(value: Any) -> str:
    return html.escape(str(value), quote=True)


def fmt_sec(value: float) -> str:
    return f"{value:.3f}s"


def fmt_num(value: float) -> str:
    return f"{value:.2f}"


def mean(values: list[float]) -> float:
    return sum(values) / len(values) if values else 0.0


def percentile(sorted_values: list[float], q: float) -> float:
    if not sorted_values:
        return 0.0
    if len(sorted_values) == 1:
        return float(sorted_values[0])
    pos = (len(sorted_values) - 1) * q / 100.0
    lo = int(math.floor(pos))
    hi = int(math.ceil(pos))
    if lo == hi:
        return float(sorted_values[lo])
    frac = pos - lo
    return float(sorted_values[lo] * (1.0 - frac) + sorted_values[hi] * frac)


def svg_line_chart(
    *,
    x_label: str,
    y_label: str,
    series: list[dict[str, Any]],
    width: int = 800,
    height: int = 360,
) -> str:
    margin_left = 60
    margin_right = 20
    margin_top = 40
    margin_bottom = 50
    plot_width = width - margin_left - margin_right
    plot_height = height - margin_top - margin_bottom

    y_values = [point["value"] for s in series for point in s["points"]]
    if not y_values:
        y_values = [0.0]
    y_max = max(y_values)
    y_min = min(0.0, min(y_values))
    if math.isclose(y_min, y_max):
        y_max = y_min + 1.0

    point_count = max((len(s["points"]) for s in series), default=1)
    x_den = max(1, point_count - 1)

    def map_x(index: int) -> float:
        return margin_left + index / x_den * plot_width

    def map_y(value: float) -> float:
        return margin_top + (y_max - value) / (y_max - y_min) * plot_height

    grid = []
    y_ticks = []
    for idx in range(6):
        val = y_min + (y_max - y_min) * idx / 5
        y = map_y(val)
        grid.append(f'<line x1="{margin_left}" y1="{y:.1f}" x2="{width - margin_right}" y2="{y:.1f}" stroke="#d3dde8" stroke-dasharray="4 5"/>')
        y_ticks.append(f'<text x="{margin_left - 10}" y="{y + 4:.1f}" text-anchor="end" font-size="12" fill="#536272">{fmt_num(val)}</text>')

    x_ticks = []
    labels = series[0]["points"] if series else []
    if labels:
        for idx, point in enumerate(labels):
            if point_count > 12 and idx not in {0, point_count // 2, point_count - 1} and idx % max(1, point_count // 8) != 0:
                continue
            x = map_x(idx)
            x_ticks.append(f'<text x="{x:.1f}" y="{height - 20}" text-anchor="middle" font-size="11" fill="#536272">{esc(point["label"])}</text>')

    paths = []
    legend = []
    for legend_idx, item in enumerate(series):
        coords = " ".join(f"L {map_x(idx):.2f} {map_y(point['value']):.2f}" for idx, point in enumerate(item["points"]))
        if coords:
            coords = "M " + coords[2:]
        paths.append(f'<path d="{coords}" fill="none" stroke="{item["color"]}" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"/>')
        for idx, point in enumerate(item["points"]):
            paths.append(f'<circle cx="{map_x(idx):.2f}" cy="{map_y(point["value"]):.2f}" r="3.4" fill="{item["color"]}" />')
        legend_x = width - margin_right - 180
        legend_y = 20 + legend_idx * 18
        legend.append(f'<line x1="{legend_x}" y1="{legend_y}" x2="{legend_x + 20}" y2="{legend_y}" stroke="{item["color"]}" stroke-width="3"/>')
        legend.append(f'<text x="{legend_x + 28}" y="{legend_y + 4}" font-size="12" fill="#30404f">{esc(item["name"])}</text>')

    return f"""
<svg xmlns="http://www.w3.org/2000/svg" width="100%" height="100%" viewBox="0 0 {width} {height}" preserveAspectRatio="xMidYMid meet">
  <rect width="100%" height="100%" fill="#ffffff"/>
  <rect x="{margin_left}" y="{margin_top}" width="{plot_width}" height="{plot_height}" rx="8" fill="#fafbfc" stroke="#e1e4e8"/>
  {''.join(grid)}
  <line x1="{margin_left}" y1="{margin_top + plot_height}" x2="{width - margin_right}" y2="{margin_top + plot_height}" stroke="#586069" stroke-width="1"/>
  <line x1="{margin_left}" y1="{margin_top}" x2="{margin_left}" y2="{margin_top + plot_height}" stroke="#586069" stroke-width="1"/>
  {''.join(y_ticks)}
  {''.join(x_ticks)}
  {''.join(paths)}
  {''.join(legend)}
  <text x="{width / 2}" y="{height - 10}" text-anchor="middle" font-size="12" fill="#586069">{esc(x_label)}</text>
  <text x="16" y="{height / 2}" text-anchor="middle" font-size="12" fill="#586069" transform="rotate(-90 16 {height / 2})">{esc(y_label)}</text>
</svg>
""".strip()


def svg_bar_chart(
    *,
    x_label: str,
    y_label: str,
    rows: list[dict[str, Any]],
    width: int = 800,
    height: int = 360,
) -> str:
    margin_left = 60
    margin_right = 20
    margin_top = 40
    margin_bottom = 70
    plot_width = width - margin_left - margin_right
    plot_height = height - margin_top - margin_bottom
    max_value = max((row["value"] for row in rows), default=1.0)
    max_value = max(max_value, 1e-9)
    bar_width = plot_width / max(1, len(rows)) * 0.72
    gap = plot_width / max(1, len(rows)) * 0.28

    def map_y(value: float) -> float:
        return margin_top + plot_height - value / max_value * plot_height

    grid = []
    ticks = []
    for idx in range(6):
        y = margin_top + idx / 5 * plot_height
        val = max_value * (1 - idx / 5)
        grid.append(f'<line x1="{margin_left}" y1="{y:.1f}" x2="{width - margin_right}" y2="{y:.1f}" stroke="#d3dde8" stroke-dasharray="4 5"/>')
        ticks.append(f'<text x="{margin_left - 10}" y="{y + 4:.1f}" text-anchor="end" font-size="12" fill="#536272">{fmt_num(val)}</text>')

    bars = []
    labels = []
    for idx, row in enumerate(rows):
        step = plot_width / max(1, len(rows))
        x = margin_left + idx * step + gap / 2
        y = map_y(row["value"])
        h = margin_top + plot_height - y
        bars.append(f'<rect x="{x:.2f}" y="{y:.2f}" width="{bar_width:.2f}" height="{h:.2f}" rx="10" fill="{row.get("color", "#3d7ea6")}"/>')
        labels.append(f'<text x="{x + bar_width / 2:.2f}" y="{y - 8:.2f}" text-anchor="middle" font-size="11" fill="#1f2e3d">{fmt_num(row["value"])}</text>')
        labels.append(f'<text x="{x + bar_width / 2:.2f}" y="{margin_top + plot_height + 18:.2f}" text-anchor="end" font-size="11" fill="#536272" transform="rotate(-28 {x + bar_width / 2:.2f} {margin_top + plot_height + 18:.2f})">{esc(row["label"])}</text>')

    return f"""
<svg xmlns="http://www.w3.org/2000/svg" width="100%" height="100%" viewBox="0 0 {width} {height}" preserveAspectRatio="xMidYMid meet">
  <rect width="100%" height="100%" fill="#ffffff"/>
  <rect x="{margin_left}" y="{margin_top}" width="{plot_width}" height="{plot_height}" rx="8" fill="#fafbfc" stroke="#e1e4e8"/>
  {''.join(grid)}
  <line x1="{margin_left}" y1="{margin_top + plot_height}" x2="{width - margin_right}" y2="{margin_top + plot_height}" stroke="#586069" stroke-width="1"/>
  <line x1="{margin_left}" y1="{margin_top}" x2="{margin_left}" y2="{margin_top + plot_height}" stroke="#586069" stroke-width="1"/>
  {''.join(ticks)}
  {''.join(bars)}
  {''.join(labels)}
  <text x="{width / 2}" y="{height - 10}" text-anchor="middle" font-size="12" fill="#586069">{esc(x_label)}</text>
  <text x="16" y="{height / 2}" text-anchor="middle" font-size="12" fill="#586069" transform="rotate(-90 16 {height / 2})">{esc(y_label)}</text>
</svg>
""".strip()


def svg_scatter_chart(
    *,
    x_label: str,
    y_label: str,
    points: list[dict[str, Any]],
    width: int = 800,
    height: int = 360,
) -> str:
    margin_left = 60
    margin_right = 20
    margin_top = 40
    margin_bottom = 50
    plot_width = width - margin_left - margin_right
    plot_height = height - margin_top - margin_bottom

    if not points:
        points = [{"x": 0.0, "y": 0.0, "r": 4.0, "label": "empty"}]
    x_min = min(point["x"] for point in points)
    x_max = max(point["x"] for point in points)
    y_min = min(0.0, min(point["y"] for point in points))
    y_max = max(point["y"] for point in points)
    if math.isclose(x_min, x_max):
        x_max = x_min + 1.0
    if math.isclose(y_min, y_max):
        y_max = y_min + 1.0

    def map_x(value: float) -> float:
        return margin_left + (value - x_min) / (x_max - x_min) * plot_width

    def map_y(value: float) -> float:
        return margin_top + (y_max - value) / (y_max - y_min) * plot_height

    grid = []
    x_ticks = []
    y_ticks = []
    for idx in range(6):
        gx = margin_left + idx / 5 * plot_width
        gy = margin_top + idx / 5 * plot_height
        xv = x_min + (x_max - x_min) * idx / 5
        yv = y_max - (y_max - y_min) * idx / 5
        grid.append(f'<line x1="{gx:.1f}" y1="{margin_top}" x2="{gx:.1f}" y2="{margin_top + plot_height}" stroke="#d3dde8" stroke-dasharray="4 5"/>')
        grid.append(f'<line x1="{margin_left}" y1="{gy:.1f}" x2="{margin_left + plot_width}" y2="{gy:.1f}" stroke="#d3dde8" stroke-dasharray="4 5"/>')
        x_ticks.append(f'<text x="{gx:.1f}" y="{height - 20}" text-anchor="middle" font-size="12" fill="#536272">{fmt_num(xv)}</text>')
        y_ticks.append(f'<text x="{margin_left - 10}" y="{gy + 4:.1f}" text-anchor="end" font-size="12" fill="#536272">{fmt_num(yv)}</text>')

    circles = []
    labels = []
    for idx, point in enumerate(points):
        color = point.get("color", "#bd632f")
        circles.append(f'<circle cx="{map_x(point["x"]):.2f}" cy="{map_y(point["y"]):.2f}" r="{point.get("r", 5):.2f}" fill="{color}" fill-opacity="0.72"/>')
        if idx < 8:
            labels.append(f'<text x="{map_x(point["x"]) + 8:.2f}" y="{map_y(point["y"]) - 8:.2f}" font-size="11" fill="#415464">{esc(point["label"])}</text>')

    return f"""
<svg xmlns="http://www.w3.org/2000/svg" width="100%" height="100%" viewBox="0 0 {width} {height}" preserveAspectRatio="xMidYMid meet">
  <rect width="100%" height="100%" fill="#ffffff"/>
  <rect x="{margin_left}" y="{margin_top}" width="{plot_width}" height="{plot_height}" rx="8" fill="#fafbfc" stroke="#e1e4e8"/>
  {''.join(grid)}
  <line x1="{margin_left}" y1="{margin_top + plot_height}" x2="{width - margin_right}" y2="{margin_top + plot_height}" stroke="#586069" stroke-width="1"/>
  <line x1="{margin_left}" y1="{margin_top}" x2="{margin_left}" y2="{margin_top + plot_height}" stroke="#586069" stroke-width="1"/>
  {''.join(x_ticks)}
  {''.join(y_ticks)}
  {''.join(circles)}
  {''.join(labels)}
  <text x="{width / 2}" y="{height - 10}" text-anchor="middle" font-size="12" fill="#586069">{esc(x_label)}</text>
  <text x="16" y="{height / 2}" text-anchor="middle" font-size="12" fill="#586069" transform="rotate(-90 16 {height / 2})">{esc(y_label)}</text>
</svg>
""".strip()


def build_cards(data: dict[str, Any]) -> list[dict[str, str]]:
    profiles = data["profiles"]
    totals = sorted(profile["total_seconds"] for profile in profiles)
    downloads = [profile["download_seconds"] for profile in profiles]
    computes = [profile["compute_seconds"] for profile in profiles]
    issues = [
        profile["issue_prepare_seconds"] + profile["issue_context_seconds"] + profile["issue_eval_seconds"]
        for profile in profiles
    ]
    return [
        {"title": "样本总数", "value": str(len(profiles)), "hint": "来自现成 JSON 数据"},
        {"title": "平均总耗时", "value": fmt_sec(mean(totals)), "hint": "单条 episode 端到端耗时"},
        {"title": "P95 总耗时", "value": fmt_sec(percentile(totals, 95)), "hint": "观察尾部慢样本"},
        {"title": "平均下载", "value": fmt_sec(mean(downloads)), "hint": "下载阶段"},
        {"title": "平均计算", "value": fmt_sec(mean(computes)), "hint": "抓取检测主计算"},
        {"title": "平均 Issues", "value": fmt_sec(mean(issues)), "hint": "判定环节开销"},
    ]


